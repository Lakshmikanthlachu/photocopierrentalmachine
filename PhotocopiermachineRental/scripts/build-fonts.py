"""Regenerate assets/css/fonts.css (Sora + Manrope as base64 data URIs) from the .woff2 files in assets/fonts.
Run from the project root:  python3 scripts/build-fonts.py"""
import base64
out = ['/* Copixa web fonts — generated by scripts/build-fonts.py */']
for fam, f, ws in [('Sora', 'sora', (500, 600, 700, 800)), ('Manrope', 'manrope', (400, 500, 600, 700, 800))]:
    for w in ws:
        b = base64.b64encode(open(f'assets/fonts/{f}-latin-{w}-normal.woff2', 'rb').read()).decode()
        out.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-weight:{w};font-display:swap;src:url(data:font/woff2;base64,{b}) format('woff2')}}")
open('assets/css/fonts.css', 'w').write('\n'.join(out) + '\n')
print('assets/css/fonts.css written')
